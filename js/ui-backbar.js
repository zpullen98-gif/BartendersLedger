function backbarCardByKey(key){ return backbarCards().find(function(c){ return 'Back Bar \u00b7 ' + c.backbarKey === key; }) || null; }
function backbarRecord(card, now){
  now = now === undefined ? Date.now() : now;
  const rec = progress.cards && progress.cards['Back Bar \u00b7 ' + card.backbarKey];
  const due = Number(rec && rec.due);
  return { record: rec, due: !!rec && Number.isFinite(due) && due > 0 && due <= now, missed: !!rec && rec.w > 0 && rec.reps === 0 };
}
