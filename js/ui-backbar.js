/* Ten bottles round-robin across the bar's groups (the group order shuffled
   each round), one of each bottle's three questions, its options shuffled.
   Each question carries the bottle's card key and no bank key, so a round
   writes one progress.quizzes row and nothing reaches progress.qa or a
   level. Fewer bottles deal what there is. */
function backbarQuizRound(){
  const lists = shuffle(backbarShelves().map(function(g){
    return shuffle(backbarEntries().filter(function(e){ return e.group === g.id && (e.quiz || []).length && (e.recall || []).some(function(r){ return r.id === 'recall'; }); }));
  })).filter(function(l){ return l.length; });
  const picked = [];
  for(let i = 0; picked.length < 10 && lists.some(function(l){ return l.length > i; }); i++){
    lists.forEach(function(l){ if(picked.length < 10 && l[i]) picked.push(l[i]); });
  }
  return picked.map(function(e){
    const q = e.quiz[Math.floor(Math.random() * e.quiz.length)];
    return { prompt: q.q, options: shuffle(q.options.slice()), answer: q.options[q.a], explain: q.explain, ckey: 'Back Bar \u00b7 ' + e.id + '/recall', backbarId: e.id };
  });
}
/* the Practise row's line: what a round deals with the bottles here */
function backbarQuizLine(){
  const n = Math.min(10, backbarEntries().filter(function(e){ return (e.quiz || []).length; }).length);
  return n >= 10 ? 'Ten questions, one bottle from each shelf in turn. It changes no level.'
    : n ? 'One question on each bottle here, across the shelves. It changes no level.' : 'The quiz opens once the bottles are here.';
}

