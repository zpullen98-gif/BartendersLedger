/* The liquor shelf, under the house's tab (4 November 2026): every bottle on
   the owner's photographs of the back bar, at #/menu/backbar, a bottle at
   #/menu/backbar/<id>. The data is js/data-backbar.js (BACKBAR_GUIDE),
   GENERATED by tools/backbar/build-backbar.mjs from reviewed fragments and
   never hand-edited.

   The namespace is backbar throughout, so nothing meets the stock's SHELF.
   What the house pours is read live from the current house (hsCurrent): At
   the house lists the drinks whose printed spec, printed ingredients, kept
   ingredient names or linked ingredient components name one of the bottle's
   match terms as a whole phrase, an occurrence inside a longer match term of
   another bottle never counting ("Stagg" inside "George T. Stagg"), the rule
   tools/backbar/schema.mjs states as houseUses; From the same house lists the
   house's producer profiles whose maker names one of its family terms
   (houseFamily). The house's name is read from the house at every draw and
   never written here; no price is drawn. Recall cards keep their own key
   space ('Back Bar \u00b7 <id>/recall') outside allDrinks, Due today and the
   levels; the quiz writes one progress.quizzes row and nothing else. Top
   level is function declarations only. */
function backbarData(){ return typeof BACKBAR_GUIDE === 'undefined' || !BACKBAR_GUIDE ? { groups: [], entries: [], confirm: [] } : BACKBAR_GUIDE; }
function backbarEntries(){ return Array.isArray(backbarData().entries) ? backbarData().entries : []; }
function backbarEntry(id){ return backbarEntries().find(function(e){ return e.id === id; }) || null; }
function backbarConfirm(){ return Array.isArray(backbarData().confirm) ? backbarData().confirm : []; }
function backbarGroups(){ return Array.isArray(backbarData().groups) ? backbarData().groups : []; }
function backbarGroup(id){ return backbarGroups().find(function(g){ return g.id === id; }) || null; }
function backbarGroupTitle(id){ const g = backbarGroup(id); return g ? g.title : ''; }
/* the bottles' groups in the bar's order, the confirm group kept for the foot */
function backbarShelves(){ return backbarGroups().filter(function(g){ return g.id !== 'confirm'; }); }
function backbarState(){ if(!state.backbar) state.backbar = { item: '', q: '' }; return state.backbar; }
function backbarHref(id){ return '#/menu/backbar' + (id ? '/' + encodeURIComponent(id) : ''); }
function backbarSafeUrl(value){ try { const url = new URL(value); return url.protocol === 'https:' ? url.href : ''; } catch(e){ return ''; } }
function backbarParas(value){ return String(value || '').split(/\n+/).filter(Boolean).map(function(p){ return '<p>' + esc(p) + '</p>'; }).join(''); }
function backbarPointer(){ return 'Allergens: confirm at lineup.'; }

/* ---- the house, read live ------------------------------------------------- */
function backbarHouse(){ return typeof hsCurrent === 'function' ? hsCurrent() : null; }
function backbarHouseName(){ const h = backbarHouse(); return h && typeof h.name === 'string' ? h.name.trim() : ''; }
/* folded as tools/backbar/schema.mjs folds: accents off, lower case, every run of other characters one space */
function backbarFold(s){
  return String(s == null ? '' : s).normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[\u2018\u2019]/g, "'")
    .toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}
function backbarKept(mark){ return mark && typeof mark === 'object' && !Array.isArray(mark) && mark.by === 'person' ? mark.value : null; }
/* every printed or kept name an item carries, each a separate text */
function backbarItemTexts(item, components){
  const out = [];
  (Array.isArray(item.spec) ? item.spec : []).forEach(function(s){ if(typeof s === 'string') out.push(s); });
  (Array.isArray(item.ingredients) ? item.ingredients : []).forEach(function(s){ if(typeof s === 'string') out.push(s); });
  const named = backbarKept(item.ingredientsNamed);
  (Array.isArray(named) ? named : []).forEach(function(s){ if(typeof s === 'string') out.push(s); });
  (components || []).forEach(function(c){
    if(c && c.kind === 'ingredient' && Array.isArray(c.itemIds) && c.itemIds.indexOf(item.id) >= 0 && typeof c.name === 'string') out.push(c.name);
  });
  return out;
}
/* the occurrences of every bottle's match terms in one text, as [start, end, id] over the folded text */
function backbarOccurrences(text, roster){
  const hay = ' ' + backbarFold(text) + ' ', out = [];
  roster.forEach(function(b){ ((b.house && b.house.match) || []).forEach(function(term){
    const t = ' ' + backbarFold(term) + ' ';
    if(t.trim() === '') return;
    for(let at = hay.indexOf(t); at >= 0; at = hay.indexOf(t, at + 1)) out.push([at, at + t.length, b.id]);
  }); });
  return out;
}
/* the house's drinks and dishes that pour this bottle, in the house's order */
function backbarUses(h, entry){
  if(!h || !entry) return [];
  const comps = Array.isArray(h.components) ? h.components : [], roster = backbarEntries();
  return [].concat(h.cocktails || [], h.dishes || []).filter(function(item){
    if(!item || !item.id || typeof item.name !== 'string' || !item.name.trim()) return false;
    return backbarItemTexts(item, comps).some(function(text){
      const occ = backbarOccurrences(text, roster);
      return occ.some(function(o){
        return o[2] === entry.id && !occ.some(function(p){ return p[2] !== o[2] && p[0] <= o[0] && p[1] >= o[1] && (p[1] - p[0]) > (o[1] - o[0]); });
      });
    });
  });
}
/* the house's producer profiles from the same house: a family term in the profile's maker */
function backbarFamily(h, entry){
  if(!h || !entry) return [];
  const terms = ((entry.house && entry.house.family) || []).map(backbarFold).filter(Boolean);
  return (Array.isArray(h.components) ? h.components : []).filter(function(c){
    const p = c && backbarKept(c.producer);
    if(!p || typeof p.who !== 'string') return false;
    const who = ' ' + backbarFold(p.who) + ' ';
    return terms.some(function(t){ return who.indexOf(' ' + t + ' ') >= 0; });
  }).map(function(c){ return { id: c.id, name: c.name, who: backbarKept(c.producer).who, itemIds: (c.itemIds || []).slice() }; });
}
function backbarHouseItem(h, id){
  if(!h || !id) return null;
  return [].concat(h.cocktails || [], h.dishes || []).find(function(x){ return x && x.id === id; }) || null;
}
/* the printed list: the person's kept names where there are some, else the printed spec */
function backbarPrinted(item){
  const kept = backbarKept(item && item.ingredientsNamed);
  return (Array.isArray(kept) ? kept : (Array.isArray(item && item.spec) ? item.spec : [])).filter(function(s){ return typeof s === 'string' && s.trim(); });
}
/* a house item's door: a drink opens its house card, a dish its World Table page where that room is reachable */
