/* At the table: every style, in the Cask Atlas (Whisky & Brandy, 5 November
   2026): each whisky style presented as a professional would at the table, at
   #/casks/style/<id>, grouped on the Cask Atlas home by family (American,
   Scotch, Irish, Japanese, Canadian). The data is js/data-caskstyles.js
   (CASK_STYLES), GENERATED by tools/caskstyles/build-caskstyles.mjs from
   reviewed fragments and never hand-edited.

   A style page reads in the liquor shelf's order: the name, Say it and the
   family; At the table (the forty-five second line large in the reading
   face, The sale under a brass rule, the ten and twenty second lines quiet
   below); How we pour it; What guests ask; The law; How it is made; How it
   tastes; How it differs; The houses to name; On our shelf (the liquor
   shelf's bottles of the style); Read the chapter; the classics it belongs
   in; Recall before you reveal and Sources, both closed; then Previous and
   Next within its family. Each Cask Atlas chapter draws its Styles to
   present, and each liquor shelf bottle of a style its style's door
   (js/ui-backbar.js reads CASK_STYLES by its shelf list).

   The cards keep their own key space ('Cask Styles · <id>/recall', src
   'Cask Styles'), outside allDrinks, Due today, the academic modes and the
   levels; Today's cask study may deal a style card that is due. The quiz
   (mode caskstyles) deals ten styles round robin across the families, one
   question each, every question carrying its card's key and no bank key, and
   writes one progress.quizzes row and nothing else. The router is the Cask
   Atlas's (js/ui-casks.js), which calls the caskStyle functions here. The
   data names no house and nobody living, and no price is drawn. Top level is
   function declarations only. */
function caskStyleData(){ return typeof CASK_STYLES === 'undefined' || !CASK_STYLES ? { families: [], entries: [] } : CASK_STYLES; }
function caskStyleEntries(){ return Array.isArray(caskStyleData().entries) ? caskStyleData().entries : []; }
function caskStyleEntry(id){ return caskStyleEntries().find(function(e){ return e.id === id; }) || null; }
function caskStyleFamilies(){ return Array.isArray(caskStyleData().families) ? caskStyleData().families : []; }
function caskStyleFamilyTitle(id){ const f = caskStyleFamilies().find(function(x){ return x.id === id; }); return f ? f.title : ''; }
function caskStyleHref(id){ return '#/casks/style/' + encodeURIComponent(id || ''); }
function caskStyleSafeUrl(value){ try { const url = new URL(value); return url.protocol === 'https:' ? url.href : ''; } catch(e){ return ''; } }
function caskStyleParas(value){ return String(value || '').split(/\n+/).filter(Boolean).map(function(p){ return '<p>' + esc(p) + '</p>'; }).join(''); }
/* the styles of a family, in roster order */
function caskStyleOfFamily(fam){ return caskStyleEntries().filter(function(e){ return e.family === fam; }); }
/* the styles that present a Cask Atlas chapter, and those that hold a liquor shelf bottle */
function caskStyleForChapter(id){ return caskStyleEntries().filter(function(e){ return (e.chapters || []).indexOf(id) >= 0; }); }
function caskStyleForBottle(id){ return caskStyleEntries().filter(function(e){ return (e.shelf || []).indexOf(id) >= 0; }); }

/* ---- the addresses: the Cask Atlas router (js/ui-casks.js) calls these ------- */
function caskStyleOpen(id){
  const s = caskState();
  state.tab = 'casks';
  s.item = caskStyleEntry(id) ? id : '';
  s.page = s.item ? 'style' : 'index';
}
/* #/casks/style/<id>; a bad or missing id lands on the Cask Atlas home */
function caskStyleRoute(parts){
  if(parts[0] !== 'casks' || parts[1] !== 'style') return false;
  let id = '';
  try { id = decodeURIComponent(parts[2] || ''); } catch(e){}
  caskStyleOpen(id);
  return true;
}
function caskStyleRouteNow(){
  const s = caskState();
  if(s.page !== 'style' || !caskStyleEntry(s.item)) return null;
  const hash = caskStyleHref(s.item);
  return { hash: hash, key: hash.slice(2) };
}
/* A revealed card, a round's results or a cask run can open the style that
   launched them: reference reading, so the run stays in the history for Back. */
function caskStyleReference(prevKey){
  return !!(state.tab === 'casks' && caskState().page === 'style' && caskState().item && /^(flashcards|quiz|casks\/practice)\//.test(prevKey || ''));
}

/* ---- the cards, the decks, the quiz and Today's cask study ----------------- */
function caskStyleKey(id){ return 'Cask Styles · ' + id + '/recall'; }
function caskStyleCards(){
  const cards = [];
  caskStyleEntries().forEach(function(e){ (e.recall || []).forEach(function(r){
    cards.push({ src: 'Cask Styles', name: r.prompt, back: r.answer, group: e.name, spec: [], caskStyleKey: e.id + '/' + r.id, itemId: e.id, drillId: r.id, ref: { id: e.id } });
  }); });
  return cards;
}
function caskStyleCardByKey(key){ return caskStyleCards().find(function(c){ return 'Cask Styles · ' + c.caskStyleKey === key; }) || null; }
function caskStyleRecord(card, now){
  now = now === undefined ? Date.now() : now;
  const rec = progress.cards && progress.cards['Cask Styles · ' + card.caskStyleKey];
  const due = Number(rec && rec.due);
  return { record: rec, due: !!rec && Number.isFinite(due) && due > 0 && due <= now, missed: !!rec && rec.w > 0 && rec.reps === 0 };
}
function caskStyleDeckDef(id){
  id = String(id || '');
  let name = 'Every style at the table', cards;
  if(id === 'caskstyles') cards = caskStyleCards();
  else if(id === 'caskstyles:again'){ name = 'Every style at the table: due or missed'; const now = Date.now(); cards = caskStyleCards().filter(function(c){ const s = caskStyleRecord(c, now); return s.due || s.missed; }); }
  else return null;
  return { name: name, preset: { only: cards, deckModes: ['caskstyles'], ordered: false }, house: true };
}
/* Today's cask study (caskDaily in js/ui-casks.js) may deal a style card that
   is due: one row per due card, in the Cask Atlas run's shape */
function caskStyleDueRows(now){
  now = now === undefined ? Date.now() : now;
  return caskStyleCards().filter(function(c){ return caskStyleRecord(c, now).due; }).map(function(c){
    return { chapter: '', style: c.itemId, id: c.drillId, q: c.name, a: c.back, why: '', key: 'Cask Styles · ' + c.caskStyleKey };
  });
}
/* the card faces: a blind front, then the answer and the style after Flip */
function caskStyleRecallHTML(card, flipped, head, front, answer, grade){
  const e = caskStyleEntry(card.itemId);
  const heading = '<div class="eyebrow">' + esc(e ? caskStyleFamilyTitle(e.family) : 'Whisky') + ' · At the table</div>';
  const question = '<div class="caskstyle-question">' + esc(card.name) + '</div>';
  if(!flipped) return '<div class="col">' + head + '<div class="panel p5 col tc study-face">' + front + heading + question
    + '<p class="small dim">Present it out loud as you would at the table, then flip.</p><button class="btn btn-brass" data-act="fc-flip">Flip</button></div></div>';
  return '<div class="col">' + head + '<div class="panel p5 col study-face">' + answer + heading + question + '<div class="caskstyle-answer">' + caskStyleParas(card.back) + '</div>'
    + '<a class="btn btn-ghost caskstyle-read-link" href="' + esc(caskStyleHref(card.itemId)) + '">Learn why: read the whole style</a>' + grade + '</div></div>';
}
/* Ten styles round robin across the families (the family order shuffled each
   round), one of each style's three questions, its options shuffled. Each
   question carries the style's card key and no bank key, so a round writes
   one progress.quizzes row and nothing reaches progress.qa, a level or a
   card. Fewer styles deal what there is. */
function caskStyleQuizRound(){
  const lists = shuffle(caskStyleFamilies().map(function(f){
    return shuffle(caskStyleOfFamily(f.id).filter(function(e){ return (e.quiz || []).length && (e.recall || []).some(function(r){ return r.id === 'recall'; }); }));
  })).filter(function(l){ return l.length; });
  const picked = [];
  for(let i = 0; picked.length < 10 && lists.some(function(l){ return l.length > i; }); i++){
    lists.forEach(function(l){ if(picked.length < 10 && l[i]) picked.push(l[i]); });
  }
  return picked.map(function(e){
    const q = e.quiz[Math.floor(Math.random() * e.quiz.length)];
    return { prompt: q.q, options: shuffle(q.options.slice()), answer: q.options[q.a], explain: q.explain, ckey: caskStyleKey(e.id), caskStyleId: e.id };
  });
}
/* the Practise row's line: what a round deals with the styles here */
function caskStyleQuizLine(){
  const n = Math.min(10, caskStyleEntries().filter(function(e){ return (e.quiz || []).length; }).length);
  return n >= 10 ? 'Ten questions, one style from each family in turn. It changes no level.'
    : n ? 'One question on each style here, across the families. It changes no level.' : 'The quiz opens once the styles are here.';
}

/* ---- the Cask Atlas home: At the table: every style ------------------------- */
function caskStyleRowHTML(e){
  /* the id is the row's focus signature (app.js focusSignature), so Back from a style puts the focus on it again */
  const shelf = caskStyleShelfNames(e);
  return '<a class="caskstyle-row" id="caskstyle-r-' + esc(e.id) + '" href="' + esc(caskStyleHref(e.id)) + '"><span class="caskstyle-row-name">' + esc(e.name) + '</span>'
    + '<span class="caskstyle-row-line">' + esc((e.lines && e.lines.s10) || '') + '</span>'
    + (shelf.length ? '<span class="caskstyle-row-foot">On the liquor shelf: ' + esc(shelf.join(', ')) + '</span>' : '') + '</a>';
}
function caskStyleHomeHTML(){
  const all = caskStyleEntries();
  if(!all.length) return '';
  const qs = all.reduce(function(n, e){ return n + (e.quiz || []).length; }, 0);
  const groups = caskStyleFamilies().map(function(f){
    const rows = caskStyleOfFamily(f.id);
    return rows.length ? '<section class="caskstyle-family" aria-labelledby="caskstyle-f-' + esc(f.id) + '"><h4 class="caskstyle-family-h" id="caskstyle-f-' + esc(f.id) + '">' + esc(f.title)
      + ' <span class="caskstyle-soft">· ' + rows.length + (rows.length === 1 ? ' style' : ' styles') + '</span></h4><div class="caskstyle-rows">' + rows.map(caskStyleRowHTML).join('') + '</div></section>' : '';
  }).join('');
  return '<section class="cask-section caskstyle-home" id="caskstyle-home" aria-labelledby="caskstyle-home-h"><h3 id="caskstyle-home-h">At the table: every style</h3>'
    + '<p>Each whisky style as you would present it to a guest: the forty-five second presentation and the sale, how we pour it, what guests ask, the law that makes it, how it is made and tastes, and the style beside it.</p>'
    + '<p class="cask-muted">' + all.length + (all.length === 1 ? ' style' : ' styles') + ' · ' + caskStyleCards().length + ' recall cards · ' + qs + ' quiz questions</p>'
    + '<div class="caskstyle-practice"><button class="btn btn-brass" data-act="caskstyle-practise" data-deck="caskstyles">Practise the cards</button>'
    + '<button class="btn btn-ghost" data-act="quiz-go" data-m="caskstyles">Take the quiz</button>'
    + '<button class="btn btn-ghost" data-act="deck" data-deck="caskstyles:again">Due or missed</button></div>'
    + groups
    + '<p class="cask-muted">The cards and the quiz keep their own record: they change no level and no Due today. These are study pages about each style, not a list of what the house pours.</p></section>';
}

/* ---- a chapter's Styles to present ------------------------------------------ */
function caskStyleChapterDoorsHTML(chapterId){
  const list = caskStyleForChapter(chapterId);
  if(!list.length) return '';
  return '<section class="cask-section caskstyle-doors" aria-labelledby="caskstyle-doors-h"><h3 id="caskstyle-doors-h">Styles to present</h3>'
    + '<p class="cask-muted">The tableside presentation of each style this chapter teaches.</p><div class="caskstyle-door-row">'
    + list.map(function(e){ return '<a class="btn btn-ghost caskstyle-door" id="caskstyle-d-' + esc(e.id) + '" href="' + esc(caskStyleHref(e.id)) + '">' + esc(e.name) + '</a>'; }).join('')
    + '</div></section>';
}

/* ---- a style's page ------------------------------------------------------------ */
function caskStyleShelfRows(e){
  const all = typeof backbarEntries === 'function' ? backbarEntries() : [];
  return (e.shelf || []).map(function(id){ return all.find(function(b){ return b.id === id; }); }).filter(Boolean);
}
function caskStyleShelfNames(e){ return caskStyleShelfRows(e).map(function(b){ return b.name; }); }
function caskStyleChapterRows(e){
  return (e.chapters || []).map(function(id){ return typeof caskChapter === 'function' ? caskChapter(id) : null; }).filter(Boolean);
}
function caskStyleCanonRows(e){
  const all = typeof COCKTAILS !== 'undefined' ? COCKTAILS : [];
  return (e.canon || []).map(function(slug){ const c = all.find(function(x){ return slugify(x.name) === slug; }); return c ? { slug: slug, name: c.name } : null; }).filter(Boolean);
}
function caskStyleDl(rows){
  rows = rows.filter(function(r){ return r[1]; });
  return rows.length ? '<dl class="caskstyle-serve">' + rows.map(function(r){ return '<div><dt>' + r[0] + '</dt><dd>' + esc(r[1]) + '</dd></div>'; }).join('') + '</dl>' : '';
}
function caskStyleSec(id, title, html, cls){
  return '<section class="caskstyle-panel' + (cls ? ' ' + cls : '') + '" aria-labelledby="caskstyle-p-' + id + '"><h3 id="caskstyle-p-' + id + '">' + title + '</h3>' + html + '</section>';
}
function caskStyleSourcesHTML(e){
  const rows = (e.sources || []).filter(function(s){ return s && s.title; });
  if(!rows.length) return '';
  return '<details class="caskstyle-sources"><summary>Sources</summary><ul>' + rows.map(function(s){
    const href = s.url ? caskStyleSafeUrl(s.url) : '';
    return '<li>' + (href ? '<a href="' + esc(href) + '" target="_blank" rel="noopener noreferrer">' + esc(s.title) + '<span class="sr-only"> (opens in a new tab)</span></a>' : esc(s.title)) + '</li>';
  }).join('') + '</ul><p class="cask-muted">Reading the sources needs a connection. In-app sources are the Cask Atlas chapters.</p></details>';
}
/* Previous and Next within the style's family, in roster order */
function caskStylePagerHTML(e){
  const fam = caskStyleOfFamily(e.family), at = fam.indexOf(e), prev = fam[at - 1], next = fam[at + 1];
  if(!prev && !next) return '';
  return '<nav class="caskstyle-pager" aria-label="' + esc('More ' + (caskStyleFamilyTitle(e.family) || 'styles')) + '">'
    + (prev ? '<a class="btn btn-ghost caskstyle-prev" href="' + esc(caskStyleHref(prev.id)) + '"><span class="caskstyle-label">Previous</span> ' + esc(prev.name) + '</a>' : '')
    + (next ? '<a class="btn btn-ghost caskstyle-next" href="' + esc(caskStyleHref(next.id)) + '"><span class="caskstyle-label">Next</span> ' + esc(next.name) + '</a>' : '')
    + '</nav>';
}
