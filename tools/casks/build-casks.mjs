/* Reviewed chapter fragments are the source; emit the classic-script data bank. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..');
const fragments=['chapters-core.json','chapters-americas.json','chapters-world.json'];
const order=['production','maturation','blending','bourbon','american-rye','american-single-malt','american-labels','canadian','irish','scotch','scotch-regions','japanese','world-whisky','cognac','armagnac-calvados','tasting','service','whisky-cocktails'];
const rows=fragments.flatMap(file=>JSON.parse(fs.readFileSync(path.join(here,file),'utf8')));
const seen=new Set();
function need(ok,message){if(!ok)throw Error(message);}
for(const c of rows){
 need(/^[a-z][a-z0-9-]+$/.test(c.id)&&!seen.has(c.id),'Duplicate or invalid chapter '+c.id);seen.add(c.id);
 for(const key of ['title','category','summary'])need(typeof c[key]==='string'&&c[key].trim(),c.id+': missing '+key);
 need(c.sections?.length>=3&&c.facts?.length>=3&&c.pitfalls?.length>=2,c.id+': insufficient teaching structure');
 need(c.recall?.length>=4&&c.quiz?.length>=3,c.id+': insufficient active recall');
 need(c.sources?.length>=2,c.id+': missing source trail');
 for(const s of c.sources)need(s.title&&/^https:\/\//.test(s.url)&&s.checked==='2026-10-27',c.id+': invalid source');
 for(const field of ['ask','say','pairing'])need(c.service&&c.service[field],c.id+': missing service '+field);
 for(const family of ['recall','quiz']){
  const ids=new Set();
  for(const item of c[family]){
   need(/^[a-z0-9-]+$/.test(item.id)&&!ids.has(item.id),c.id+': invalid '+family+' ID');ids.add(item.id);
   need(item.q&&typeof item.q==='string',c.id+': missing prompt');
   if(family==='recall')need(item.a&&typeof item.a==='string',c.id+': missing answer');
   else{
    need(item.options?.length===4&&new Set(item.options).size===4,c.id+': four distinct choices required');
    need(Number.isInteger(item.answer)&&item.answer>=0&&item.answer<4&&item.why,c.id+': missing quiz answer/explanation');
   }
  }
 }
 need(!/[\u2013\u2014]/.test(JSON.stringify(c)),c.id+': use punctuation without long dashes');
}
need(order.length===rows.length&&order.every(id=>seen.has(id)),'The ordered curriculum and chapter fragments disagree');
for(const c of rows)for(const id of c.related||[])need(seen.has(id)&&id!==c.id,c.id+': invalid related chapter '+id);
const sorted=order.map(id=>rows.find(c=>c.id===id));
const output='/* GENERATED by tools/casks/build-casks.mjs from reviewed chapter fragments.\n   Stable chapter/prompt IDs are study keys. Never hand-edit this file. */\nvar CASK_CHAPTERS = '+JSON.stringify(sorted,null,2)+';\n';
const dest=path.join(root,'js/data-casks.js');
if(process.argv.includes('--check'))need(fs.existsSync(dest)&&fs.readFileSync(dest,'utf8')===output,'Cask data differs from its reviewed source; run node tools/casks/build-casks.mjs');
else fs.writeFileSync(dest,output);
console.log(JSON.stringify({chapters:sorted.length,recall:sorted.reduce((n,c)=>n+c.recall.length,0),quiz:sorted.reduce((n,c)=>n+c.quiz.length,0),sources:new Set(sorted.flatMap(c=>c.sources.map(s=>s.url))).size,bytes:Buffer.byteLength(output),mode:process.argv.includes('--check')?'checked':'written'}));
